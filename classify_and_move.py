def classify_question(q_text, subject):
    """Classify a general question into the correct chapter based on keyword matching."""
    if subject not in SUBJECT_KEYWORDS:
        return None
    
    text = q_text.lower()
    best_match = None
    best_score = 0
    
    for keywords, chapter_name in SUBJECT_KEYWORDS[subject]:
        score = 0
        for kw in keywords:
            if kw.lower() in text:
                score += 1
        if score > best_score:
            best_score = score
            best_match = chapter_name
    
    # Only return if we have at least one keyword match
    return best_match if best_score > 0 else None

def get_chapter_id(subject, chapter_name):
    """Get the chapter ID from meta.json for a given chapter name."""
    if subject in meta:
        for ch in meta[subject]['chapters']:
            if ch['name'] == chapter_name:
                return ch['id']
    return None

