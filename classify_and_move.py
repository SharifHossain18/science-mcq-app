    fpath = os.path.join(boards_dir, fname)
    with open(fpath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    modified = False
    for q in data:
        if q['chapter'] == 'General':
            total_general += 1
            subject = q['subject']
            q_text = q['question']
            # Clean HTML tags for matching
            clean_text = re.sub(r'<[^>]+>', '', q_text)
            
            new_chapter = classify_question(clean_text, subject)
            
            if new_chapter and new_chapter != 'General':
                q['chapter'] = new_chapter
                modified = True
                moved += 1
                stats[subject][new_chapter] += 1
            else:
                unclassified += 1
                unclassified_list.append((fname, q['id'], subject, clean_text[:100]))
    
    if modified:
        with open(fpath, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

