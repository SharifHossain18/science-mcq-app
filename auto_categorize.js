let grandTotalMoved = 0;

Object.keys(rules).forEach(subject => {
    const prefix = getSubjectFilePrefix(subject);
    const generalFilePath = path.join(CHAPTERS_DIR, `${prefix}_ch_1.json`);

    if (!fs.existsSync(generalFilePath)) {
        console.log(`[${subject}] No General file found. Skipping.`);
        return;
    }

    const generalQuestions = JSON.parse(fs.readFileSync(generalFilePath, 'utf8'));
    console.log(`[${subject}] Total Uncategorized: ${generalQuestions.length}`);

    if (generalQuestions.length === 0) {
        console.log(`[${subject}] Already completely sorted!\n`);
        return;
    }

    const subjectRules = rules[subject];
    const subjectChapters = meta[subject].chapters;

    const remaining = [];
    const moveQueues = {}; // targetChapterId => []

    // Pre-initialize move queues for all target chapters
    subjectChapters.forEach(ch => {
        if (ch.id !== 'ch_1') {
            moveQueues[ch.id] = [];
        }
    });

    generalQuestions.forEach(q => {
        // Combined search block
        const questionText = (q.question || '').toLowerCase();
        const optionsText = (q.options || []).join(' ').toLowerCase();
        const explanationText = (q.explanation || '').toLowerCase();
        const textBlock = `${questionText} ${optionsText} ${explanationText}`;

        const matchedChapters = [];

        Object.keys(subjectRules).forEach(chId => {
            const keywords = subjectRules[chId];
            const hasMatch = keywords.some(keyword => {
                const normalizedKeyword = keyword.toLowerCase();
                return textBlock.includes(normalizedKeyword);
            });

            if (hasMatch) {
                matchedChapters.push(chId);
            }
        });

        // 100% Safe categorization: Must match EXACTLY ONE chapter rule
        if (matchedChapters.length === 1) {
            const targetChId = matchedChapters[0];
            const chapterMeta = subjectChapters.find(ch => ch.id === targetChId);
            
            // Clone and update the chapter field to match the official name
            const updatedQuestion = { ...q, chapter: chapterMeta.name };
            moveQueues[targetChId].push(updatedQuestion);
        } else {
            remaining.push(q);
        }
    });

    // Save movements to files
    let movedForSubject = 0;
    Object.keys(moveQueues).forEach(targetChId => {
        const toMove = moveQueues[targetChId];
        if (toMove.length === 0) return;

        const targetFilePath = path.join(CHAPTERS_DIR, `${prefix}_${targetChId}.json`);
        let chapterList = [];

        if (fs.existsSync(targetFilePath)) {
            chapterList = JSON.parse(fs.readFileSync(targetFilePath, 'utf8'));
        }

        chapterList.push(...toMove);
        fs.writeFileSync(targetFilePath, JSON.stringify(chapterList, null, 2), 'utf8');

        const chapterName = subjectChapters.find(ch => ch.id === targetChId).name;
        console.log(`  -> Moved ${toMove.length} questions to ${chapterName} (${targetChId})`);
        movedForSubject += toMove.length;
    });

    // Write back remaining questions to _ch_1.json
    fs.writeFileSync(generalFilePath, JSON.stringify(remaining, null, 2), 'utf8');
    
    console.log(`[${subject}] Result: Moved ${movedForSubject} questions, ${remaining.length} remaining in General.\n`);
    grandTotalMoved += movedForSubject;
});

console.log("==========================================");
console.log(`Auto-Categorization Complete!`);
console.log(`Total questions successfully categorized: ${grandTotalMoved}`);
console.log("==========================================");
